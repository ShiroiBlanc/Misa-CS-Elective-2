drop policy if exists "Customers read roles" on public.roles;
create policy "Customers read roles" on public.roles for select
  to authenticated using (true);

drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select
  to authenticated using (id = auth.uid() or public.is_admin());
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update
  to authenticated using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "Customers read categories" on public.categories;
create policy "Customers read categories" on public.categories for select
  to authenticated using (true);
drop policy if exists "Admins manage categories" on public.categories;
create policy "Admins manage categories" on public.categories for all
  to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Customers read products" on public.products;
create policy "Customers read products" on public.products for select
  to authenticated using (true);
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all
  to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders" on public.orders for select
  to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update
  to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Customers read own order items" on public.order_items;
create policy "Customers read own order items" on public.order_items for select
  to authenticated using (
    exists (
      select 1 from public.orders o
      where o.id = order_items.order_id
        and (o.user_id = auth.uid() or public.is_admin())
    )
  );

