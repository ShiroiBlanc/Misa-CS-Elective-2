create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  customer_role bigint;
begin
  select id into customer_role from public.roles where role = 'customer';
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'firstname', ''),
    coalesce(new.raw_user_meta_data ->> 'lastname', ''),
    customer_role
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.role = 'admin'
  );
$$;

create or replace function public.prevent_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.role_id is distinct from new.role_id and not public.is_admin() then
    raise exception 'Only administrators can change roles';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
  before update on public.profiles
  for each row execute procedure public.prevent_profile_role_change();

create or replace function public.checkout_order(
  p_items jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  order_id bigint;
  item jsonb;
  current_product public.products%rowtype;
  calculated_total numeric(12, 2) := 0;
  item_quantity integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Cart cannot be empty';
  end if;

  insert into public.orders (user_id, status, total)
  values (auth.uid(), 'pending', 0)
  returning id into order_id;

  for item in select value from jsonb_array_elements(p_items)
  loop
    item_quantity := (item ->> 'quantity')::integer;
    if item_quantity is null or item_quantity <= 0 then
      raise exception 'Invalid quantity';
    end if;

    select * into current_product
    from public.products
    where id = (item ->> 'product_id')::bigint
    for update;

    if not found or current_product.stock < item_quantity then
      raise exception 'Product is unavailable or out of stock';
    end if;

    insert into public.order_items (order_id, product_id, unit_price, quantity)
    values (order_id, current_product.id, current_product.price, item_quantity);
    update public.products
    set stock = stock - item_quantity
    where id = current_product.id;
    calculated_total := calculated_total + current_product.price * item_quantity;
  end loop;

  update public.orders
  set total = calculated_total, status = 'done'
  where id = order_id;
  return order_id;
exception
  when others then
    delete from public.orders where id = order_id;
    raise;
end;
$$;

